class LanguageManager {
    constructor() {
        this.currentLang = localStorage.getItem('udvega_lang') || 'teluglish';
    }

    setLanguage(langKey) {
        if (!i18nDict[langKey]) return;
        this.currentLang = langKey;
        localStorage.setItem('udvega_lang', langKey);
        this.applyTranslations();
    }

    t(key) {
        return i18nDict[this.currentLang][key] || i18nDict['en'][key] || key;
    }

    applyTranslations() {
        const langSelect = document.getElementById('languageSelect');
        if (langSelect) langSelect.value = this.currentLang;

        // Update Nav Tabs
        const tabMonitor = document.querySelector('[data-tab="tab-monitor"]');
        if (tabMonitor) tabMonitor.innerHTML = `<i class="fa-solid fa-chart-line"></i> ${this.t('tabMonitor')}`;

        const tabApta = document.querySelector('[data-tab="tab-apta"]');
        if (tabApta) tabApta.innerHTML = `<i class="fa-solid fa-user-doctor"></i> ${this.t('tabApta')} <span class="badge-unread" id="aptaUnread" style="display:none;">1</span>`;

        const tabSound = document.querySelector('[data-tab="tab-frequency"]');
        if (tabSound) tabSound.innerHTML = `<i class="fa-solid fa-compact-disc"></i> ${this.t('tabSound')}`;

        const tabGames = document.querySelector('[data-tab="tab-games"]');
        if (tabGames) tabGames.innerHTML = `<i class="fa-solid fa-gamepad"></i> ${this.t('tabGames')}`;

        const tabHistory = document.querySelector('[data-tab="tab-history"]');
        if (tabHistory) tabHistory.innerHTML = `<i class="fa-solid fa-clock-rotate-left"></i> ${this.t('tabHistory')}`;

        // Header Buttons
        const serialBtn = document.getElementById('btnConnectSerial');
        if (serialBtn) serialBtn.innerHTML = `<i class="fa-solid fa-plug"></i> ${this.t('serialConnect')}`;

        const bleBtn = document.getElementById('btnConnectBLE');
        if (bleBtn) bleBtn.innerHTML = `<i class="fa-brands fa-bluetooth-b"></i> ${this.t('bleConnect')}`;

        const simBtnText = document.getElementById('simBtnText');
        if (simBtnText && !window.app?.isSimulating) simBtnText.textContent = this.t('startSim');
    }
}

const i18n = new LanguageManager();
